// Generates code from the contracts in shared/ for every language that consumes them.
//
//   bun scripts/gen.ts            all languages (needs go and uv on PATH; CI runs this)
//   bun scripts/gen.ts --only=ts  TypeScript only
//
// Outputs are committed. CI regenerates and fails if `git diff` is not empty.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { compileFromFile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";
import YAML from "yaml";

const shared = resolve(import.meta.dir, "..");
const repo = resolve(shared, "..");
const only = process.argv.find((a) => a.startsWith("--only="))?.split("=")[1];

const HEADER = "// Code generated by shared/scripts/gen.ts. DO NOT EDIT.\n";

const SCHEMAS = [
  "schemas/domain.schema.json",
  "schemas/protocol/client-message.schema.json",
  "schemas/protocol/server-message.schema.json",
  "schemas/jobs/job.schema.json",
];

const moduleName = (schemaPath: string) => basename(schemaPath, ".schema.json");

async function genTypeScript() {
  const out = join(shared, "generated/ts");
  mkdirSync(out, { recursive: true });
  const modules: string[] = [];

  for (const schema of SCHEMAS) {
    const file = join(shared, schema);
    const ts = await compileFromFile(file, {
      cwd: dirname(file),
      bannerComment: HEADER,
      additionalProperties: false,
      unreachableDefinitions: true,
      style: { semi: true, singleQuote: false },
    });
    const name = moduleName(schema);
    writeFileSync(join(out, `${name}.ts`), ts);
    modules.push(name);
  }

  const api = await openapiTS(new URL(`file://${join(shared, "openapi.yaml")}`));
  writeFileSync(join(out, "openapi.ts"), HEADER + astToString(api));

  // Each schema file re-declares the domain types it references, so every module is exported
  // under a namespace, and the top-level unions are also exported by name.
  const index =
    HEADER +
    modules.map((m) => `export * as ${NAMESPACES[m]} from "./${m}";`).join("\n") +
    `\nexport type { ClientMessage } from "./client-message";` +
    `\nexport type { ServerMessage } from "./server-message";` +
    `\nexport type { Job } from "./job";` +
    `\nexport type { paths as ApiPaths, components as ApiComponents } from "./openapi";\n`;
  writeFileSync(join(out, "index.ts"), index);
  console.log(`ts: ${modules.length + 1} files -> shared/generated/ts`);
}

const NAMESPACES: Record<string, string> = {
  domain: "Domain",
  "client-message": "Client",
  "server-message": "Server",
  job: "Jobs",
};

function run(cmd: string, args: string[], cwd = repo) {
  const r = spawnSync(cmd, args, { cwd, stdio: "inherit" });
  if (r.error || r.status !== 0) {
    throw new Error(`${cmd} ${args.join(" ")} failed${r.error ? `: ${r.error.message}` : ""}`);
  }
}

function genGo() {
  const out = join(repo, "game/internal/contracts");
  mkdirSync(out, { recursive: true });
  run("go", [
    "run",
    "github.com/atombender/go-jsonschema@v0.18.0",
    "--package",
    "contracts",
    "--only-models",
    "--output",
    join(out, "contracts_gen.go"),
    ...SCHEMAS.map((s) => join(shared, s)),
  ]);
  console.log("go: game/internal/contracts/contracts_gen.go");
}

// oapi-codegen reads OpenAPI 3.0 only and can't follow refs into the domain schema, so api/ is
// generated from a 3.0 copy: `type: [x, "null"]` and `oneOf: [x, {type: "null"}]` become
// `nullable`, and domain refs are inlined.
// The copy is committed next to the code so handler tests can validate responses against it.
function openapi30(): string {
  const doc = YAML.parse(readFileSync(join(shared, "openapi.yaml"), "utf8"));
  const domain = JSON.parse(readFileSync(join(shared, "schemas/domain.schema.json"), "utf8")).$defs;
  const ext = "./schemas/domain.schema.json#/$defs/";
  const walk = (node: unknown): void => {
    if (Array.isArray(node)) {
      node.forEach(walk);
      return;
    }
    if (!node || typeof node !== "object") return;
    const o = node as Record<string, unknown>;
    if (Array.isArray(o.oneOf) && o.oneOf.length === 2) {
      const isNull = (s: unknown) => !!s && typeof s === "object" && (s as Record<string, unknown>).type === "null";
      const other = o.oneOf.find((s) => !isNull(s));
      if (other && o.oneOf.some(isNull)) {
        delete o.oneOf;
        const converted = structuredClone(other) as Record<string, unknown>;
        // OpenAPI 3.0 ignores siblings of $ref, including nullable. allOf keeps the
        // reference and makes nullability visible to validators and generators.
        if (typeof converted.$ref === "string") Object.assign(o, { allOf: [converted], nullable: true });
        else Object.assign(o, converted, { nullable: true });
      }
    }
    if (typeof o.$ref === "string" && o.$ref.startsWith(ext)) {
      const def = structuredClone(domain[o.$ref.slice(ext.length)]);
      delete o.$ref;
      Object.assign(o, def);
    }
    if (Array.isArray(o.type) && o.type.includes("null")) {
      o.type = o.type.find((t) => t !== "null");
      o.nullable = true;
    }
    Object.values(o).forEach(walk);
  };
  doc.openapi = "3.0.3";
  walk(doc);
  return `# ${HEADER.slice(3)}${YAML.stringify(doc)}`;
}

function genGoApi() {
  const out = join(repo, "api/internal/contracts");
  mkdirSync(out, { recursive: true });
  const spec = join(out, "openapi30.gen.yaml");
  writeFileSync(spec, openapi30());
  run("go", [
    "run",
    "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.4.1",
    "-generate",
    "types,std-http-server",
    "-package",
    "contracts",
    "-o",
    join(out, "contracts_gen.go"),
    spec,
  ]);
  // The generated router stores security scopes under a string context key (SA1029).
  const code = join(out, "contracts_gen.go");
  const ignore = "//\n//lint:file-ignore SA1029 generated by oapi-codegen\n";
  writeFileSync(code, readFileSync(code, "utf8").replace(/^package contracts$/m, `${ignore}$&`));
  console.log("go: api/internal/contracts/contracts_gen.go");
}

function genPython() {
  const out = join(repo, "worker/src/schmegettes_worker/contracts");
  mkdirSync(out, { recursive: true });
  run("uvx", [
    "--from",
    "datamodel-code-generator==0.28.5",
    "datamodel-codegen",
    "--input",
    join(shared, "schemas"),
    "--input-file-type",
    "jsonschema",
    "--output",
    out,
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.13",
    "--disable-timestamp",
  ]);
  console.log("python: worker/src/schmegettes_worker/contracts/");
}

await genTypeScript();
if (only !== "ts") {
  genGo();
  genGoApi();
  genPython();
}
